/* ============================================================
   СЧЁТЧИК ТЕМПА: спектральный поток, автокорреляция, гребёнка.

   Отдаёт по звуку три числа: темп (ударов в минуту), смещение первой
   доли и уверенность — насколько выражен найденный период. Всё, что
   студия делает с сеткой долей дальше (рисование, магнит, правка
   руками), живёт в app.js; здесь только счёт.

   ФАЙЛ РАБОТАЕТ В ДВУХ РОЛЯХ, и это нарочно:
     • подключённый script-тегом в окно, он даёт ТЕМП.оценить() —
       синхронный счёт на месте (им пользуется самопроверка и он же
       запасной путь, если рабочий поток не завёлся);
     • запущенный как new Worker('tempo.js'), он же становится рабочим
       потоком: подтягивает fft.js и отвечает на сообщения.
   Одна копия алгоритма вместо двух: разъехаться им негде.

   ------------------------------------------------------------
   ПОЧЕМУ СПЕКТРАЛЬНЫЙ ПОТОК, А НЕ ОГИБАЮЩАЯ ГРОМКОСТИ

   Раньше темп считался по громкости: энергия кадрами по 5 мс в трёх
   полосах, наросла — значит начало звука. На щелчках это работало
   безупречно, а на настоящей музыке уверенность выходила 5–8 %:
   на плотном сведении общая громкость между ударами почти не
   проседает — компрессор её ровняет, гитары и голос заполняют паузы,
   и вершина автокорреляции у «Кирпичей» была не выше, чем у белого
   шума. Хуже того, песня и её же минусовка давали РАЗНЫЕ темпы
   (126,7 и 93,7): по такому числу сетку строить нельзя.

   Спектральный поток смотрит не на громкость, а на ПОЯВЛЕНИЕ НОВОЙ
   энергии в отдельных полосах спектра. Удар барабана — это всплеск
   сразу в сотне полос, даже если общая громкость не шелохнулась,
   потому что ровно в этот миг чуть притих кто-то другой. Замерено на
   тех же песнях: вершина автокорреляции поднялась с 0,055 до 0,254,
   уверенность — с 9 % до 41 %, а песня и минусовка сошлись на одном
   темпе (126,73 и 126,71) с точностью до сотых.

   Как считается:
     1. звук прореживается до ~11 кГц (ТЕМП_ЗВУК) усреднением: выше
        5 кГц про доли ничего нового нет, а считать вчетверо дешевле;
     2. КПФ окном Ханна в ТЕМП_ОКНО отсчётов (≈93 мс) с шагом 5 мс
        (ТЕМП_ЧАСТОТА = 200 кадров в секунду);
     3. каждая полоса сжимается логарифмом log(1 + 1000·|X|). Без
        сжатия поток считал бы только громкие полосы — бочку и малый
        барабан, — а тихая гитара, входящая ровно по доле, не весила
        бы ничего. Со сжатием каждая полоса говорит своё «стало вдвое
        громче» одинаково внятно, чем громко бы она ни звучала;
     4. поток = сумма ПОЛОЖИТЕЛЬНЫХ приращений по всем полосам:
        появление энергии — начало звука, затухание — нет;
     5. автокорреляция потока по лагам, отвечающим 60–190 ударам
        в минуту: у ритмичной музыки поток похож сам на себя ровно
        через долю;
     6. предпочтение обычного темпа (весТемпа): у ровных щелчков
        60 и 120 совпадают одинаково хорошо, и без этого веса выбор
        между ними был бы случайным. Клоним к 120 — самому обычному
        темпу; ровно так же поступают все счётчики темпа;
     7. гребёнка: период и фаза уточняются вместе, мелким шагом.

   ЗАДЕРЖКА ОКНА — то, о чём легко забыть и получить сетку, съехавшую
   на десятую долю секунды. Кадр КПФ смотрит на ТЕМП_ОКНО отсчётов
   назад, и новая энергия попадает в него не тогда, когда удар
   случился, а когда он ВЪЕХАЛ в окно. Поэтому кадр относится не
   к своему левому краю, а к середине того куска, который в него
   только что вошёл: (ТЕМП_ОКНО − шаг/2) отсчётов правее. Без этой
   поправки щелчки, поставленные на 0,10 с, находились на 0,015 —
   ровно на длину окна раньше.
   ------------------------------------------------------------ */

/* В рабочем потоке БПФ надо подтянуть самому; в окне его уже принёс
   script-тег. location.search переносит номер версии (?v=1.12.1),
   иначе поток получил бы из кэша fft.js прошлой сборки. */
if (typeof window === 'undefined' && typeof importScripts === 'function') {
  importScripts('fft.js' + (self.location ? self.location.search : ''));
}

const ТЕМП_МИН = 60;        // нижняя граница перебора, ударов в минуту
const ТЕМП_МАКС = 190;      // верхняя
const ТЕМП_ЧАСТОТА = 200;   // кадров в секунду у потока начал (5 мс на кадр)
const ТЕМП_ОТРЕЗОК = 120;   // сколько секунд песни разбираем
const ТЕМП_ЦЕНТР = 120;     // самый обычный темп: к нему клонимся при двойственности
const ТЕМП_РАЗБРОС = 0.9;   // ширина этого предпочтения, в октавах
const ТЕМП_ДВОЙНОЙ = 0.85;  // насколько близко подошёл удвоенный, чтобы признать двойственность
const ТЕМП_ЗВУК = 11025;    // до какой частоты прореживаем звук перед КПФ
const ТЕМП_ОКНО = 1024;     // окно КПФ в отсчётах: при 11 кГц это ≈93 мс
const ТЕМП_СЖАТИЕ = 1000;   // крутизна логарифмического сжатия полос
/* Вершина автокорреляции, выше которой совпадение периода уже
   безоговорочное. Ровно 1,0 не бывает даже у безупречно ритмичной
   песни: удары не повторяются отсчёт в отсчёт, а поток шумит. Это
   потолок шкалы уверенности, см. её разбор ниже. */
const ТЕМП_ПОТОЛОК = 0.6;

let кэшБПФ = null;
function бпфОкна() {
  if (!кэшБПФ) кэшБПФ = БПФ.сделатьБПФ(ТЕМП_ОКНО);
  return кэшБПФ;
}

/* Спектральный поток начал по звуку одного канала.
   Возвращает null, если разбирать нечего (слишком коротко). */
function спектральныйПоток(данные, sr) {
  if (!данные || !данные.length || !(sr > 0)) return null;
  /* Прореживаем усреднением: заодно и фильтр против наложения
     частот — верх, которого мы всё равно не смотрим, не заворачивается
     вниз ложными началами. */
  const дец = Math.max(1, Math.round(sr / ТЕМП_ЗВУК));
  const чд = sr / дец;
  const всего = Math.min(данные.length, Math.round(ТЕМП_ОТРЕЗОК * sr));
  const n = Math.floor(всего / дец);
  if (n < ТЕМП_ОКНО * 2) return null;
  const x = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0;
    const о = i * дец;
    for (let j = 0; j < дец; j++) s += данные[о + j];
    x[i] = s / дец;
  }

  const шаг = Math.max(1, Math.round(чд / ТЕМП_ЧАСТОТА));
  const частота = чд / шаг;
  const кадров = Math.floor((n - ТЕМП_ОКНО) / шаг) + 1;
  if (кадров < 64) return null;

  const бпф = бпфОкна();
  const окно = new Float64Array(ТЕМП_ОКНО);
  for (let i = 0; i < ТЕМП_ОКНО; i++) {
    окно[i] = 0.5 - 0.5 * Math.cos((2 * Math.PI * i) / ТЕМП_ОКНО);
  }
  const полос = ТЕМП_ОКНО / 2;
  const re = new Float64Array(ТЕМП_ОКНО);
  const im = new Float64Array(ТЕМП_ОКНО);
  let прош = new Float32Array(полос);
  let тек = new Float32Array(полос);
  const поток = new Float32Array(кадров);

  /* ДВА КАДРА ЗА ОДНО КПФ: чётный кладём в вещественную часть,
     нечётный — в мнимую, обратно спектры разбираются эрмитовой
     симметрией. Тот же приём, которым pitch-worker.js гонит через
     одно преобразование левый и правый каналы. Кадров тут двадцать
     четыре тысячи на песню, и лишняя половина счёта — это лишние
     триста миллисекунд. */
  for (let ф = 0; ф < кадров; ф += 2) {
    const оA = ф * шаг;
    const оB = (ф + 1) * шаг;
    const естьB = ф + 1 < кадров;
    for (let i = 0; i < ТЕМП_ОКНО; i++) {
      re[i] = x[оA + i] * окно[i];
      im[i] = естьB ? x[оB + i] * окно[i] : 0;
    }
    бпф(re, im, false);
    for (let пара = 0; пара < 2; пара++) {
      const кадр = ф + пара;
      if (кадр >= кадров) break;
      for (let k = 1; k < полос; k++) {
        const j = ТЕМП_ОКНО - k;
        let ar, ai;
        if (пара === 0) { ar = 0.5 * (re[k] + re[j]); ai = 0.5 * (im[k] - im[j]); }
        else { ar = 0.5 * (im[k] + im[j]); ai = -0.5 * (re[k] - re[j]); }
        // Логарифм: см. пункт 3 в разборе наверху
        тек[k] = Math.log(1 + ТЕМП_СЖАТИЕ * Math.sqrt(ar * ar + ai * ai));
      }
      if (кадр > 0) {
        let s = 0;
        for (let k = 1; k < полос; k++) {
          const рост = тек[k] - прош[k];
          if (рост > 0) s += рост;   // затухание началом звука не считается
        }
        поток[кадр] = s;
      }
      const t = прош; прош = тек; тек = t;
    }
  }
  // Задержка окна: см. разбор наверху
  return { поток, частота, кадров, задержка: (ТЕМП_ОКНО - шаг / 2) / чд };
}

/* Насколько охотно верим в такой темп. Ровные щелчки одинаково хорошо
   объясняются и 60, и 120 ударами в минуту — выбор между ними делает
   этот вес, клонящий к обычному человеческому темпу. */
function весТемпа(bpm) {
  const о = Math.log2(bpm / ТЕМП_ЦЕНТР) / ТЕМП_РАЗБРОС;
  return Math.exp(-0.5 * о * о);
}

/* Оценка темпа по одному каналу. Возвращает null, если ритма нет
   вовсе (тишина, ровный гул, слишком короткий кусок). */
function оценить(данные, sr) {
  const о = спектральныйПоток(данные, sr);
  if (!о) return null;
  const { поток, частота, кадров, задержка } = о;

  // Автокорреляции нужен ноль в среднем, иначе совпадёт всё со всем
  let сумма = 0;
  for (let i = 0; i < кадров; i++) сумма += поток[i];
  const среднее = сумма / кадров;
  const x = new Float32Array(кадров);
  let дисп = 0;
  for (let i = 0; i < кадров; i++) { x[i] = поток[i] - среднее; дисп += x[i] * x[i]; }
  дисп /= кадров;
  if (!(дисп > 1e-12)) return null;   // тишина или ровный гул — ритма нет

  const лагМин = Math.max(2, Math.floor(60 * частота / ТЕМП_МАКС));
  const лагМакс = Math.min(кадров - 2, Math.ceil(60 * частота / ТЕМП_МИН));
  if (лагМакс <= лагМин + 1) return null;
  /* На кадр шире с каждой стороны — только чтобы было чем уточнять
     вершину, стоящую на самом краю полосы. Выбираем лучший всё равно
     внутри полосы: вылезать за 60–190 ударов в минуту нельзя. */
  const лагНиз = Math.max(2, лагМин - 1);
  const лагВерх = Math.min(кадров - 2, лагМакс + 1);

  const ак = new Float64Array(лагВерх + 2);
  const оценка = new Float64Array(лагВерх + 2);
  let сумАК = 0;
  for (let lag = лагНиз; lag <= лагВерх; lag++) {
    let s = 0;
    const n = кадров - lag;
    for (let i = 0; i < n; i++) s += x[i] * x[i + lag];
    ак[lag] = (s / n) / дисп;
    if (lag >= лагМин && lag <= лагМакс) сумАК += ак[lag];
    оценка[lag] = ак[lag] * весТемпа(60 * частота / lag);
  }
  const фон = сумАК / (лагМакс - лагМин + 1);

  let лучший = лагМин;
  for (let lag = лагМин; lag <= лагМакс; lag++) {
    if (оценка[lag] > оценка[лучший]) лучший = lag;
  }
  /* Уточняем период между кадрами: вершина автокорреляции почти
     наверняка стоит не ровно на кадре, а между двумя, и без этой
     поправки темп мерился бы с шагом больше удара в минуту. */
  let точный = лучший;
  if (лучший > лагНиз && лучший < лагВерх) {
    const a = ак[лучший - 1];
    const b = ак[лучший];
    const c = ак[лучший + 1];
    const зн = a - 2 * b + c;
    if (зн < 0) {
      const δ = 0.5 * (a - c) / зн;
      if (Math.abs(δ) < 0.5) точный = лучший + δ;
    }
  }

  /* Двойственность: вдвое медленнее или вдвое быстрее объясняет ту же
     музыку почти так же хорошо. Молчать об этом нельзя — именно здесь
     автомат и промахивается чаще всего. */
  const бли = (lag) => {
    const l = Math.round(lag);
    let м = -1;
    for (let k = l - 1; k <= l + 1; k++) {
      if (k >= лагМин && k <= лагМакс && ак[k] > м) м = ак[k];
    }
    return м;
  };
  const соперник = Math.max(бли(лучший * 2), бли(лучший / 2));
  const двойственный = ак[лучший] > 0 && соперник >= ТЕМП_ДВОЙНОЙ * ак[лучший];

  /* Гребёнка: где стоят доли и с каким шагом ТОЧНО. Автокорреляция
     дала период с точностью до кадра, а этого мало: ошибка в сотую
     долю кадра за две минуты разводит сетку с музыкой на полтакта.
     Поэтому перебираем период мелким шагом вокруг найденного и вместе
     с ним фазу, складывая поток начал ровно там, где сетка ставит
     доли, и делим на число долей — чтобы более частая сетка не
     выигрывала одним лишь числом слагаемых.

     Соседние кадры входят вполовину: удар редко попадает ровно
     в кадр потока. */
  let лучПериод = точный;
  let лучшаяФаза = 0;
  let лучшаяСумма = -1;
  for (let d = -20; d <= 20; d++) {
    const P = точный + d * 0.05;
    if (P < 2) continue;
    const шагов = Math.max(1, Math.round(P));
    for (let s = 0; s < шагов; s++) {
      const off = s * P / шагов;
      let сум = 0;
      let кол = 0;
      for (let k = 0; ; k++) {
        const i = Math.round(off + k * P);
        if (i >= кадров) break;
        сум += поток[i] + 0.5 * (поток[i - 1] || 0) + 0.5 * (поток[i + 1] || 0);
        кол++;
      }
      if (!кол) continue;
      const среднееНаДолю = сум / кол;
      if (среднееНаДолю > лучшаяСумма) {
        лучшаяСумма = среднееНаДолю;
        лучПериод = P;
        лучшаяФаза = off;
      }
    }
  }
  точный = лучПериод;

  const bpm = 60 * частота / точный;
  const период = 60 / bpm;
  const фаза = ((лучшаяФаза / частота + задержка) % период + период) % период;

  /* УВЕРЕННОСТЬ — честная мера того, насколько выбранный период
     выражен, а не украшение для глаза.

     Считаем её по одному числу: ак[лучший] — доле потока, которая
     объясняется повторением ровно через этот период (автокорреляция
     нормирована, так что это коэффициент корреляции от 0 до 1).
     Отсчитываем от ФОНА — среднего совпадения по всей полосе перебора:
     он показывает, сколько набегает само собой, без всякого ритма.
     Потолок — ТЕМП_ПОТОЛОК: выше него шкала упирается, потому что
     единицы не достигает даже идеально ритмичная запись.

     Почему не через разброс (z-мера). Пробовали: (пик − фон) / σ.
     На шуме выходило 2,3, на «Кирпичах» — 1,9, то есть настоящая
     музыка выглядела ХУЖЕ шума. Причина понятна: у музыки, кроме
     вершины на доле, есть вершины на полудоле и на такте, и они же
     раздувают σ. Разброс тут меряет богатство ритма, а не его
     выраженность, — и в уверенность не годится.

     Что получилось на деле (спектральный поток, те же записи):
       ровные щелчки       — 100 %
       «Кирпичи», рэп      —  41 %
       её же минусовка     —  44 %
       «Ленинград»         —  47 %
       белый шум           —   4 %
       тишина              —  темпа нет вовсе, null
     Высоко на чётком ритме, средне на настоящей музыке, низко на шуме
     и ничего на тишине — ровно так шкала и должна себя вести.

     Двойственный темп уверенности не прибавляет — половиним. */
  let уверенность = (ак[лучший] - фон) / Math.max(1e-6, ТЕМП_ПОТОЛОК - фон);
  уверенность = Math.min(1, Math.max(0, уверенность));
  if (двойственный) уверенность *= 0.5;

  return {
    bpm: +bpm.toFixed(2),
    фаза: +фаза.toFixed(4),
    уверенность: +уверенность.toFixed(3),
    двойственный,
    пик: +ак[лучший].toFixed(3),
    соперник: +Math.max(соперник, 0).toFixed(3),
    фон: +фон.toFixed(4),
    разобрано: +(кадров / частота).toFixed(1),
  };
}

self.ТЕМП = { оценить, ТЕМП_МИН, ТЕМП_МАКС, ТЕМП_ОТРЕЗОК };

/* Роль рабочего потока. Дорожка приезжает копией (владение передано),
   обратно уходит готовая оценка — несколько чисел.

   Номер заказа возвращаем как есть: заказы накладываются (открыли
   редактор, тут же досчиталась минусовка), и студия разбирает ответы
   по номеру. Без него второй заказ отбирал бы ответ у первого. */
if (typeof window === 'undefined' && typeof importScripts === 'function') {
  self.onmessage = (e) => {
    const m = e.data || {};
    try {
      const t0 = Date.now();
      const итог = оценить(new Float32Array(m.данные), +m.sampleRate || 44100);
      self.postMessage({ type: 'done', номер: m.номер, итог, мс: Date.now() - t0 });
    } catch (err) {
      self.postMessage({
        type: 'error', номер: m.номер,
        error: String((err && err.message) || err),
      });
    }
  };
}
