/* ============================================================
   БПФ по основанию 2, на месте. Общее на всю студию.

   Зачем отдельным файлом. Быстрое преобразование Фурье нужно двоим:
   смене тональности (pitch-worker.js, фазовый вокодер) и счётчику
   темпа (tempo.js, спектральный поток). Раньше оно жило внутри
   вокодера; когда темпу понадобился спектр, выбор был между второй
   копией того же кода и общим файлом. Две копии одного БПФ — это
   починка в одной и молчаливая ошибка в другой, поэтому общий файл.

   Почему своё, а не из dsp.js: dsp.js живёт только в приложении
   (его тянет разделение вокала), а тональность и темп нужны и на сайте.

   Подключается тремя способами и работает во всех:
     • script-тегом в окно — index.html, до app.js;
     • importScripts('fft.js' + location.search) из рабочего потока;
     • после подключения БПФ лежит в self.БПФ (в окне self === window).
   Хвост location.search переносит в поток номер версии (?v=1.12.1),
   иначе браузер подсунул бы потоку файл прошлой сборки из кэша.
   ============================================================ */

/* Возвращает готовое к работе преобразование на n точек: таблицы
   синусов и перестановки считаются один раз, дальше только счёт.

   бпф(re, im, обратное) правит массивы НА МЕСТЕ. Обратное делит на n. */
function сделатьБПФ(n) {
  const уровней = Math.round(Math.log2(n));
  if (2 ** уровней !== n) throw new Error('БПФ: нужна степень двойки');
  const cosT = new Float64Array(n / 2);
  const sinT = new Float64Array(n / 2);
  for (let i = 0; i < n / 2; i++) {
    cosT[i] = Math.cos((2 * Math.PI * i) / n);
    sinT[i] = Math.sin((2 * Math.PI * i) / n);
  }
  const rev = new Uint32Array(n);
  for (let i = 0; i < n; i++) {
    let x = i, r = 0;
    for (let j = 0; j < уровней; j++) { r = (r << 1) | (x & 1); x >>= 1; }
    rev[i] = r;
  }
  return function бпф(re, im, обратное) {
    for (let i = 0; i < n; i++) {
      const j = rev[i];
      if (j > i) {
        let t = re[i]; re[i] = re[j]; re[j] = t;
        t = im[i]; im[i] = im[j]; im[j] = t;
      }
    }
    for (let size = 2; size <= n; size *= 2) {
      const half = size / 2;
      const step = n / size;
      for (let i = 0; i < n; i += size) {
        for (let j = i, k = 0; j < i + half; j++, k += step) {
          const l = j + half;
          const c = cosT[k];
          const s = обратное ? sinT[k] : -sinT[k];
          const tre = re[l] * c - im[l] * s;
          const tim = re[l] * s + im[l] * c;
          re[l] = re[j] - tre;
          im[l] = im[j] - tim;
          re[j] += tre;
          im[j] += tim;
        }
      }
    }
    if (обратное) for (let i = 0; i < n; i++) { re[i] /= n; im[i] /= n; }
  };
}

// И в окне, и в рабочем потоке self — это глобальный объект
self.БПФ = { сделатьБПФ };
