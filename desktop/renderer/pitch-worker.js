/* ============================================================
   СМЕНА ТОНАЛЬНОСТИ — расчёт в рабочем потоке.

   Что делает: поднимает или опускает песню на ±N полутонов, НЕ меняя
   ни темпа, ни длины. Отдаёт новые дорожки той же длины, отсчёт
   в отсчёт.

   ПОЧЕМУ ЦЕЛИКОМ И ЗАРАНЕЕ, А НЕ НА ЛЕТУ. Тональность выбирают один
   раз перед пением. Значит, считать её в реальном времени незачем —
   а вот цена реального времени велика: пришлось бы врезать узел
   в живую цепь, и его задержку и его же расписание понадобилось бы
   учитывать и плееру, и отрезкам оригинала, и записи видео. Считая
   заранее в новый буфер той же длины, мы не трогаем НИЧЕГО: плеер,
   расписание отрезков, выгрузка .wav и запись видео получают буфер
   с прежней разметкой и прежней длиной и знать не знают, что песню
   перенесли в другую тональность.

   ПОЧЕМУ ДЛИНА ОБЯЗАНА СОВПАДАТЬ ОТСЧЁТ В ОТСЧЁТ. Вся разметка
   студии — времена: строки, слова, огибающая голоса, сетка долей,
   отрезки оригинала. Уедь длина хоть на отсчёт — уедет всё, и
   человек об этом даже не узнает, пока не запоёт мимо.

   ЧЕМ СЧИТАЕМ. Своим фазовым вокодером на чистом JS.

   Почему не Signalsmith Stretch, хотя качество у него лучше:
   готовая сборка в npm (signalsmith-stretch, MIT) есть, но она
   собрана ТОЛЬКО как AudioWorklet — модуль подкладывается через
   blob:-адрес, а сам счёт идёт внутри WebAssembly. Для нас это три
   отказа сразу: в рабочем потоке AudioWorklet не существует вовсе;
   политика безопасности сайта (script-src 'self') запрещает и
   blob:-скрипт, и WebAssembly; а ослаблять её ради тональности
   нельзя. Компилировать библиотеку самим — это emscripten, которого
   на машине нет. Поэтому считаем сами.

   КАК УСТРОЕН СДВИГ. Растяжение × пересчёт частоты:
     1. фазовый вокодер растягивает запись в r = 2^(полутонов/12) раз,
        не меняя высоты;
     2. получившееся пересчитывается обратно в r раз — длина
        возвращается к исходной, а вся высота умножается на r.

   Фазовый вокодер — обычное КПФ с окном Ханна, шаг синтеза
   постоянный (четверть окна: перекрытие ровно то, на котором сумма
   квадратов окна постоянна), шаг анализа плавает и равен ему,
   делённому на r. Между кадрами фаза продвигается не «как было»,
   а по ИСТИННОЙ частоте полосы (отклонение приведённое к ±π,
   классическая оценка мгновенной частоты).

   ФАЗОВАЯ СИНХРОНИЗАЦИЯ ПО ПИКАМ (identity phase locking,
   Laroche & Dolson 1999). Если каждую полосу вести независимо,
   к середине песни соседние полосы одного и того же голоса
   разъезжаются по фазе, и звук становится «водянистым» — это самая
   заметная беда наивного вокодера. Поэтому фазу считаем только
   в вершинах спектра, а всем полосам вокруг вершины даём РОВНО ТУ ЖЕ
   поправку: тогда их фазовые отношения внутри вершины не меняются
   вовсе, и голос остаётся голосом.

   ТРАНЗИЕНТЫ. На резком ударе накопленная фазовая поправка размазывает
   атаку. Замечаем удар по всплеску спектрального потока и на таком
   кадре сбрасываем поправку в ноль: кадр ложится со своей исходной
   фазой, то есть внутренне когерентным. Для рэпа, где ударов больше,
   чем распевов, это слышно сразу.

   КАНАЛЫ ОБРАБАТЫВАЮТСЯ СВЯЗАННО. Поправка считается по СЕРЕДИНЕ
   (полусумме каналов) и применяется к левому и правому одинаково.
   Значит, разница фаз и уровней между каналами сохраняется точно,
   какой была. Иначе стереокартина расползается, а у нас это вдвойне
   критично: минусовка сделана вычитанием середины, и любая
   несогласованная правка каналов вернула бы в неё вокал.

   Оба канала едут через ОДНО КПФ: левый кладётся в вещественную часть,
   правый — в мнимую, спектры разделяются эрмитовой симметрией.
   Прямое и обратное — по одному на кадр вместо трёх и двух.

   ПЕРЕСЧЁТ ЧАСТОТЫ — оконный sinc (ядро Блэкмана), со срезом 1/r при
   сжатии: без среза верх записи заворачивался бы вниз слышимым
   призвуком. Ядро считается таблицей по долям отсчёта один раз
   на вызов.

   Всё во float32, без единого лишнего пересэмплирования.
   ============================================================ */

/* Здесь — только страховка от бессмыслицы: на двух октавах растяжение
   доходит до четырёх, а от записи не остаётся ничего.

   РАБОЧИЙ предел — ±7 полутонов (дальше гласные уезжают в «бурундука»
   или в «бочку», и петь по такой минусовке невозможно), но он живёт
   не здесь, а в студии (ТОН_МАКС в app.js): это решение о том, что
   предлагать человеку, а не о том, что умеет движок. Разделение
   не умозрительное — самопроверка гоняет движок на целую октаву,
   чтобы убедиться, что 220 Гц и правда становятся 440. */
const МАКС_ПОЛУТОНОВ = 24;

/* ------------------------------------------------------------
   БПФ по основанию 2, на месте. Своё, а не из dsp.js: dsp.js живёт
   только в приложении, а тональность нужна и на сайте.
   ------------------------------------------------------------ */
function сделатьБПФ(n) {
  const уровней = Math.round(Math.log2(n));
  if (2 ** уровней !== n) throw new Error('БПФ: нужна степень двойки');
  const cosT = new Float64Array(n / 2);
  const sinT = new Float64Array(n / 2);
  for (let i = 0; i < n / 2; i++) {
    cosT[i] = Math.cos((2 * Math.PI * i) / n);
    sinT[i] = Math.sin((2 * Math.PI * i) / n);
  }
  const rev = new Uint32Array(n);
  for (let i = 0; i < n; i++) {
    let x = i, r = 0;
    for (let j = 0; j < уровней; j++) { r = (r << 1) | (x & 1); x >>= 1; }
    rev[i] = r;
  }
  return function бпф(re, im, обратное) {
    for (let i = 0; i < n; i++) {
      const j = rev[i];
      if (j > i) {
        let t = re[i]; re[i] = re[j]; re[j] = t;
        t = im[i]; im[i] = im[j]; im[j] = t;
      }
    }
    for (let size = 2; size <= n; size *= 2) {
      const half = size / 2;
      const step = n / size;
      for (let i = 0; i < n; i += size) {
        for (let j = i, k = 0; j < i + half; j++, k += step) {
          const l = j + half;
          const c = cosT[k];
          const s = обратное ? sinT[k] : -sinT[k];
          const tre = re[l] * c - im[l] * s;
          const tim = re[l] * s + im[l] * c;
          re[l] = re[j] - tre;
          im[l] = im[j] - tim;
          re[j] += tre;
          im[j] += tim;
        }
      }
    }
    if (обратное) for (let i = 0; i < n; i++) { re[i] /= n; im[i] /= n; }
  };
}

/* Отклонение фазы к ±π: без этого приведения оценка мгновенной
   частоты бессмысленна — фаза за шаг успевает намотать много оборотов */
function кПи(x) {
  return x - 2 * Math.PI * Math.round(x / (2 * Math.PI));
}

/* Окно КПФ: около 46 мс. Короче — распев звучит «зернисто», длиннее —
   удары размазываются. На 44,1 и 48 кГц это 2048 отсчётов. */
function размерОкна(sr) {
  if (sr >= 64000) return 4096;
  if (sr >= 32000) return 2048;
  return 1024;
}

/* ------------------------------------------------------------
   Ядро пересчёта частоты: оконный sinc по долям отсчёта.

   Полуширина берётся в периодах sinc, поэтому при срезе она
   растягивается: срез вдвое ниже — вдвое больше отводов. Каждая
   доля нормируется по сумме, чтобы постоянная составляющая не гуляла
   от доли к доле (иначе на низах слышен ровный шорох).
   ------------------------------------------------------------ */
const РЕЗ_ПЕРИОДОВ = 12;   // полуширина ядра, периодов sinc
const РЕЗ_ДОЛЕЙ = 1024;    // на сколько долей отсчёта разбита таблица

function сделатьЯдро(срез) {
  const пол = Math.max(2, Math.ceil(РЕЗ_ПЕРИОДОВ / срез));
  const отводов = 2 * пол;
  const таблица = new Float32Array((РЕЗ_ДОЛЕЙ + 1) * отводов);
  for (let д = 0; д <= РЕЗ_ДОЛЕЙ; д++) {
    const доля = д / РЕЗ_ДОЛЕЙ;
    const база = д * отводов;
    let сумма = 0;
    for (let t = 0; t < отводов; t++) {
      const x = (t - пол + 1) - доля;
      const y = срез * x;
      const s = Math.abs(y) < 1e-9 ? срез : срез * Math.sin(Math.PI * y) / (Math.PI * y);
      const wn = (x + пол) / отводов;
      const w = 0.42 - 0.5 * Math.cos(2 * Math.PI * wn) + 0.08 * Math.cos(4 * Math.PI * wn);
      const v = s * w;
      таблица[база + t] = v;
      сумма += v;
    }
    const k = 1 / (сумма || 1e-9);
    for (let t = 0; t < отводов; t++) таблица[база + t] *= k;
  }
  return { таблица, пол, отводов };
}

/* Пересчёт: out[j] = x[j·шаг + сдвиг]. Длина выхода задаётся снаружи —
   именно так длина возвращается к исходной отсчёт в отсчёт. */
function пересчитать(x, длина, шаг, сдвиг, ядро) {
  const { таблица, пол, отводов } = ядро;
  const out = new Float32Array(длина);
  const n = x.length;
  for (let j = 0; j < длина; j++) {
    const p = j * шаг + сдвиг;
    const i0 = Math.floor(p);
    const д = Math.round((p - i0) * РЕЗ_ДОЛЕЙ);
    const база = д * отводов;
    let s = 0;
    const нач = i0 - пол + 1;
    if (нач >= 0 && нач + отводов <= n) {
      for (let t = 0; t < отводов; t++) s += таблица[база + t] * x[нач + t];
    } else {
      for (let t = 0; t < отводов; t++) {
        const i = нач + t;
        if (i >= 0 && i < n) s += таблица[база + t] * x[i];
      }
    }
    out[j] = s;
  }
  return out;
}

/* ------------------------------------------------------------
   Сам сдвиг. L и R — дорожки одинаковой длины (моно приходит
   двумя ссылками на один и тот же массив). Возвращает две новые
   дорожки ровно той же длины.
   ------------------------------------------------------------ */
function сдвинуть(L, R, sr, полутонов, отчёт) {
  const всего = L.length;
  const r = Math.pow(2, полутонов / 12);
  const N = размерОкна(sr);
  const Hs = N / 4;                 // шаг синтеза: перекрытие 75 %
  const бпф = сделатьБПФ(N);

  const окно = new Float32Array(N);
  for (let i = 0; i < N; i++) окно[i] = 0.5 - 0.5 * Math.cos((2 * Math.PI * i) / N);

  /* Сколько растянутого звука понадобится пересчёту. Кадр f кладётся
     в выход по адресу f·Hs, а его середина отвечает моменту записи
     f·Hs/r — отсюда и сдвиг на полокна ниже, в пересчёте. */
  const нужно = Math.ceil((всего - 1) * r + N / 2) + 4;
  const кадров = Math.max(1, Math.ceil(нужно / Hs) + 1);
  const растянуто = (кадров - 1) * Hs + N;

  /* Не const: растянутые дорожки на песне в три минуты — это сотни
     мегабайт, и после пересчёта их надо отпустить сборщику мусора,
     не дожидаясь конца функции. */
  let выхL = new Float32Array(растянуто);
  let выхR = new Float32Array(растянуто);
  let вес = new Float32Array(растянуто);

  const zRe = new Float64Array(N);
  const zIm = new Float64Array(N);
  const бинов = N / 2 + 1;
  // Спектры каналов и середины на текущем кадре
  const лRe = new Float64Array(бинов), лIm = new Float64Array(бинов);
  const пRe = new Float64Array(бинов), пIm = new Float64Array(бинов);
  const сRe = new Float64Array(бинов), сIm = new Float64Array(бинов);
  const мод = new Float64Array(бинов);
  // Что помним с прошлого кадра: спектр середины и поправку по каждой полосе.
  // Фазу прошлого кадра берём отсюда — atan2 считается только в вершинах.
  const прRe = new Float64Array(бинов), прIm = new Float64Array(бинов);
  const прМод = new Float64Array(бинов);
  const прПопр = new Float64Array(бинов);
  const попр = new Float64Array(бинов);
  const вершины = new Int32Array(бинов);

  let предПоз = 0;
  const шагАнализа = Hs / r;
  const ТРАНЗИЕНТ = 0.5;   // доля прироста спектра, после которой это удар

  for (let f = 0; f < кадров; f++) {
    const поз = Math.round(f * шагАнализа) - N / 2;
    const hA = f === 0 ? Hs : поз - предПоз;
    предПоз = поз;

    // Окно с обоими каналами сразу: левый — вещественная часть, правый — мнимая
    for (let i = 0; i < N; i++) {
      const j = поз + i;
      const w = окно[i];
      if (j >= 0 && j < всего) { zRe[i] = L[j] * w; zIm[i] = R[j] * w; }
      else { zRe[i] = 0; zIm[i] = 0; }
    }
    бпф(zRe, zIm, false);

    // Разделяем спектры каналов и считаем середину
    let энергия = 0;
    for (let k = 0; k < бинов; k++) {
      const k2 = (N - k) % N;
      const lr = 0.5 * (zRe[k] + zRe[k2]);
      const li = 0.5 * (zIm[k] - zIm[k2]);
      const ar = 0.5 * (zRe[k] - zRe[k2]);
      const ai = 0.5 * (zIm[k] + zIm[k2]);
      лRe[k] = lr; лIm[k] = li;
      пRe[k] = ai; пIm[k] = -ar;      // деление на i
      const mr = 0.5 * (lr + ai);
      const mi = 0.5 * (li - ar);
      сRe[k] = mr; сIm[k] = mi;
      const m = Math.sqrt(mr * mr + mi * mi);
      мод[k] = m;
      энергия += m;
    }

    /* Удар: спектр вырос сразу во многих полосах. Считаем только
       прирост — затухание ударом не бывает. */
    let прирост = 0;
    for (let k = 0; k < бинов; k++) {
      const d = мод[k] - прМод[k];
      if (d > 0) прирост += d;
    }
    const удар = f > 0 && энергия > 1e-9 && прирост / энергия > ТРАНЗИЕНТ;

    if (f === 0 || удар || энергия <= 1e-12) {
      // Кадр ложится со своей фазой: поправки нет
      попр.fill(0);
    } else {
      // Вершины спектра: выше обоих соседей и обоих через одного
      let вершин = 0;
      for (let k = 2; k < бинов - 2; k++) {
        const m = мод[k];
        if (m > мод[k - 1] && m > мод[k + 1] && m > мод[k - 2] && m > мод[k + 2]) {
          вершины[вершин++] = k;
        }
      }
      if (!вершин) {
        // Ни одной вершины (ровный шум) — ведём по самой сильной полосе
        let л = 0;
        for (let k = 1; k < бинов; k++) if (мод[k] > мод[л]) л = k;
        вершины[вершин++] = л;
      }
      for (let v = 0; v < вершин; v++) {
        const p = вершины[v];
        const φ = Math.atan2(сIm[p], сRe[p]);
        const φп = Math.atan2(прIm[p], прRe[p]);
        const ω = (2 * Math.PI * p) / N;
        // Истинная частота полосы, рад на отсчёт
        const ист = ω + кПи(φ - φп - hA * ω) / hA;
        const Δ = кПи((φп + прПопр[p]) + Hs * ист - φ);
        /* Область влияния вершины — до середины между нею и соседней.
           Внутри области поправка ОДНА И ТА ЖЕ: в этом и состоит
           синхронизация по пикам, фазовые отношения внутри вершины
           остаются нетронутыми. */
        const от = v === 0 ? 0 : ((вершины[v - 1] + p) >> 1) + 1;
        const до = v === вершин - 1 ? бинов - 1 : ((p + вершины[v + 1]) >> 1);
        for (let k = от; k <= до; k++) попр[k] = Δ;
      }
    }

    // Поворот обоих каналов на одну и ту же поправку
    for (let k = 0; k < бинов; k++) {
      const Δ = попр[k];
      const c = Math.cos(Δ), s = Math.sin(Δ);
      const lr = лRe[k], li = лIm[k];
      const pr = пRe[k], pi = пIm[k];
      let nlr = lr * c - li * s, nli = lr * s + li * c;
      let npr = pr * c - pi * s, npi = pr * s + pi * c;
      /* Нулевая полоса и полоса Найквиста у вещественного сигнала
         обязаны остаться вещественными — иначе после обратного
         преобразования каналы протекли бы друг в друга. Содержимого
         в них при окне Ханна почти нет, так что мнимую часть просто
         снимаем. */
      if (k === 0 || k === N / 2) { nli = 0; npi = 0; }
      // Обратная упаковка: снова левый в вещественную часть, правый в мнимую
      zRe[k] = nlr - npi;
      zIm[k] = nli + npr;
      if (k > 0 && k < N / 2) {
        const k2 = N - k;
        zRe[k2] = nlr + npi;
        zIm[k2] = -nli + npr;
      }
      прRe[k] = сRe[k]; прIm[k] = сIm[k];
      прМод[k] = мод[k];
      прПопр[k] = Δ;
    }
    бпф(zRe, zIm, true);

    const база = f * Hs;
    for (let i = 0; i < N; i++) {
      const w = окно[i];
      выхL[база + i] += zRe[i] * w;
      выхR[база + i] += zIm[i] * w;
      вес[база + i] += w * w;
    }

    if (отчёт && (f % 64 === 0 || f === кадров - 1)) отчёт(f + 1, кадров);
  }

  /* Делим на сумму квадратов окна. В середине она постоянна (для окна
     Ханна с шагом в четверть — ровно 1,5), а на краях считается сама:
     так начало и конец не оказываются тише остальной записи. */
  for (let i = 0; i < растянуто; i++) {
    const w = вес[i];
    if (w > 1e-6) { выхL[i] /= w; выхR[i] /= w; }
    else { выхL[i] = 0; выхR[i] = 0; }
  }

  /* Обратный пересчёт частоты. Длина задана жёстко (всего), поэтому
     совпадение отсчёт в отсчёт обеспечено самим устройством цикла,
     а не удачным округлением. */
  вес = null;
  const ядро = сделатьЯдро(Math.min(1, 1 / r));
  const итогL = пересчитать(выхL, всего, r, N / 2, ядро);
  выхL = null;
  const итогR = L === R ? итогL : пересчитать(выхR, всего, r, N / 2, ядро);
  выхR = null;
  return { L: итогL, R: итогR };
}

self.onmessage = (e) => {
  const msg = e.data || {};
  try {
    const полутонов = Math.max(-МАКС_ПОЛУТОНОВ,
      Math.min(МАКС_ПОЛУТОНОВ, Math.round(+msg.полутонов || 0)));
    const каналы = (msg.каналы || []).map((b) => new Float32Array(b));
    if (!каналы.length) throw new Error('нет дорожек');
    const L = каналы[0];
    const R = каналы.length > 1 ? каналы[1] : каналы[0];
    const t0 = Date.now();
    const отчёт = (кадр, кадров) => {
      self.postMessage({
        type: 'progress',
        /* Кадры — не вся работа: после них идёт пересчёт частоты,
           примерно десятая часть времени. Поэтому до сотни полоса
           доходит только в сообщении «готово». */
        percent: Math.min(90, Math.round((кадр / кадров) * 90)),
        кадр, кадров,
      });
    };
    const { L: нL, R: нR } = сдвинуть(L, R, +msg.sampleRate || 44100, полутонов, отчёт);
    const выход = каналы.length > 1 ? [нL, нR] : [нL];
    self.postMessage(
      {
        type: 'done',
        каналы: выход.map((x) => x.buffer),
        полутонов,
        мс: Date.now() - t0,
      },
      выход.map((x) => x.buffer),
    );
  } catch (err) {
    self.postMessage({ type: 'error', error: String((err && err.message) || err) });
  }
};
