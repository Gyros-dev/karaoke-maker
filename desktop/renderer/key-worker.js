/* ============================================================
   ТОНАЛЬНОСТЬ ПЕСНИ — расчёт в рабочем потоке.

   Что делает: слушает ЧИСТЫЙ ВОКАЛ и говорит, в какой тональности
   песня. Не сдвигает её — сдвиг живёт отдельно (pitch-worker.js);
   здесь только распознавание.

   ЗАЧЕМ. Тональность выбирают вслепую: жмут ±1 и слушают, пока
   не станет удобно петь. Зная тональность песни, человек видит,
   куда он её переносит: «ля минор, а с +2 будет си минор».

   ПОЧЕМУ ПО ЧИСТОМУ ВОКАЛУ, А НЕ ПО ПЕСНЕ. Метод Маклауда ищет одну
   основную частоту и работает на ОДНОГОЛОСОМ звуке. На полном миксе,
   где играют бас, гитара и барабаны, он честно выдаёт мусор. Чистый
   вокал у нас есть — его оставляет разделение (см. removeVocals),
   и это ровно тот сигнал, для которого метод и придуман. Нет
   разделения — нет и ответа: соврать было бы хуже, чем промолчать.

   КАК СЧИТАЕМ.
     1. Режем вокал окнами по 2048 отсчётов с шагом вполовину.
     2. В каждом окне pitchy находит высоту и «чистоту» — насколько
        уверенно она найдена. Берём только уверенные: на придыханиях
        и согласных высоты нет вовсе, и её догадки только испортят счёт.
     3. Каждую высоту переводим в ноту и копим в двенадцати корзинах
        (до, до-диез, ре…), взвешивая уверенностью.
     4. Сравниваем получившийся портрет с двадцатью четырьмя
        образцами Крумхансл — по одному на каждую мажорную и минорную
        тональность — и берём самый похожий.

   Считает поток, а не страница: три минуты вокала — это тысячи окон,
   и на слабой машине интерфейс на секунду-другую замер бы.
   ============================================================ */

const ОКНО = 2048;
const ШАГ = 1024;
const ЧИСТОТА = 0.93;      // ниже — это не нота, а шум
const НИЖЕ_НЕ_ГОЛОС = 65;  // Гц: ниже поют разве что в подвале
const ВЫШЕ_НЕ_ГОЛОС = 1300;

/* Образцы Крумхансл и Кесслера: насколько каждая ступень «своя»
   в мажоре и в миноре. Числа из их работы 1982 года, ими же
   пользуются почти все определители тональности. */
const МАЖОР = [6.35, 2.23, 3.48, 2.33, 4.38, 4.09, 2.52, 5.19, 2.39, 3.66, 2.29, 2.88];
const МИНОР = [6.33, 2.68, 3.52, 5.38, 2.60, 3.53, 2.54, 4.75, 3.98, 2.69, 3.34, 3.17];

/* Мера похожести — обычная корреляция Пирсона. Она не смотрит
   на громкость: важно, КАК распределены ноты, а не сколько их. */
function корреляция(a, b) {
  const n = a.length;
  let sa = 0;
  let sb = 0;
  for (let i = 0; i < n; i++) { sa += a[i]; sb += b[i]; }
  const ma = sa / n;
  const mb = sb / n;
  let верх = 0;
  let ka = 0;
  let kb = 0;
  for (let i = 0; i < n; i++) {
    const da = a[i] - ma;
    const db = b[i] - mb;
    верх += da * db;
    ka += da * da;
    kb += db * db;
  }
  const низ = Math.sqrt(ka * kb);
  return низ > 0 ? верх / низ : 0;
}

function повернуть(профиль, на) {
  const out = new Array(12);
  for (let i = 0; i < 12; i++) out[i] = профиль[(i + на) % 12];
  return out;
}

self.onmessage = async (e) => {
  const { pcm, rate } = e.data;
  try {
    const { PitchDetector } = await import('./pitchy.js');
    const звук = new Float32Array(pcm);
    const детектор = PitchDetector.forFloat32Array(ОКНО);
    const корзины = new Float64Array(12);
    let нот = 0;

    for (let от = 0; от + ОКНО <= звук.length; от += ШАГ) {
      const [гц, чистота] = детектор.findPitch(звук.subarray(от, от + ОКНО), rate);
      if (!(чистота >= ЧИСТОТА)) continue;
      if (!(гц > НИЖЕ_НЕ_ГОЛОС && гц < ВЫШЕ_НЕ_ГОЛОС)) continue;
      // Гц → номер ноты (69 — это ля первой октавы, 440 Гц)
      const нота = 69 + 12 * Math.log2(гц / 440);
      const класс = ((Math.round(нота) % 12) + 12) % 12;
      корзины[класс] += чистота;
      нот++;
    }

    if (нот < 40) {
      // Слишком мало уверенных нот — честнее промолчать
      self.postMessage({ ok: false, мало: true, нот });
      return;
    }

    let лучший = null;
    for (let тоника = 0; тоника < 12; тоника++) {
      for (const лад of ['мажор', 'минор']) {
        const образец = повернуть(лад === 'мажор' ? МАЖОР : МИНОР, (12 - тоника) % 12);
        const мера = корреляция([...корзины], образец);
        if (!лучший || мера > лучший.мера) лучший = { тоника, лад, мера };
      }
    }
    self.postMessage({ ok: true, тоника: лучший.тоника, лад: лучший.лад,
      мера: лучший.мера, нот, корзины: [...корзины] });
  } catch (err) {
    self.postMessage({ ok: false, error: String((err && err.message) || err) });
  }
};
