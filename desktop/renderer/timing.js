/* ============================================================
   Разметка во времени: строки, слова, распев

   Чистая арифметика — ни холста, ни звука, ни состояния студии.
   Отсюда берут ответы и дорожка, и просмотр, и сцена «Караоке»,
   и запись видео: подсветка обязана быть одинаковой на всех
   четырёх поверхностях, а для этого считать её должен один код.

   Файл подключается и в окно студии, и в проверку из Node —
   наружу отдаётся через module, как в align.js. Быстрые проверки
   (node --test test/) гоняют именно его: полная самопроверка
   в Electron идёт минуты, а правка здесь бывает в одну строку.
   ============================================================ */

// Короче этого строку и слово не делаем: иначе край не ухватить мышью,
// а подсветка мигает быстрее, чем глаз успевает заметить
const MIN_SPAN = 0.08;

/* ---------- Слова внутри строки ----------
   Если слова размечены вручную или распознаванием, берём их метки.
   Иначе делим время строки между словами пропорционально длине:
   длинное слово поётся дольше короткого. Это грубее точной разметки,
   но подсветка идёт по словам, а не ползёт сквозь них. */
function splitWords(text) {
  // Пробелы приклеиваем к предыдущему слову, чтобы подсветка шла сплошняком
  const parts = text.match(/\S+\s*/g);
  return parts ? parts : [];
}

/* Сдвиг слов относительно их меток.

   Метки слов заданы абсолютным временем, а строку могло подтянуть
   к настоящему вступлению голоса (см. lineStart) — тогда слова едут
   за ней ровно на ту же величину, иначе подсветка бежала бы впереди
   певца. Без голосовой дорожки и у строки, начало которой поставили
   руками, сдвиг нулевой.

   Это ЕДИНСТВЕННАЯ разница между показанным временем слова (дорожка,
   мышь, клавиши, поля инспектора, указатель) и его меткой в разметке.
   Всё, что пишет метки, обязано перевести показанное время сюда —
   иначе край встанет не туда, куда его привели. Так и было: тянешь
   начало слова к 11,90, а оно встаёт на 12,12 — ровно на сдвиг
   строки мимо. */
function сдвигСлов(line, span) {
  return span.start - line.time;
}

function меткаПоПоказанному(line, span, t) {
  return t - сдвигСлов(line, span);
}

/* Разложить куски по весу в промежутке: длинное слово поётся дольше
   короткого. Одна на всех: так делится строка без разметки и так же
   раскладываются слова, не поместившиеся в укороченную строку. */
function разложитьПоВесу(куски, от, до) {
  const weights = куски.map((c) => Math.max(1, String(c).trim().length));
  const total = weights.reduce((a, b) => a + b, 0);
  const width = Math.max(0.05, до - от);
  const out = [];
  let acc = от;
  for (let i = 0; i < куски.length; i++) {
    const dur = width * (weights[i] / total);
    out.push({ start: acc, end: acc + dur });
    acc += dur;
  }
  return out;
}

/* Слова не поместились в строку — раскладываем те, что вышли за конец.

   Беда, которую это лечит: человек укорачивал ошибочно длинную строку,
   и вместе с ней съёживались ВСЕ слова разом. Прежний код ужимал
   разметку общим множителем, сохраняя пропорции заведомо неверной
   раскладки: слова, стоявшие в начале правильно, уезжали влево,
   и строку приходилось раскладывать заново кнопкой «распределить».

   Теперь всё, что помещается, остаётся ровно там, где стоит, а вышедшие
   за конец раскладываются по весу в оставшемся куске. Саму разметку это
   не переписывает: вернули конец назад — вернулись и метки. Переписывает
   её только правка слова, и тоже из показанного (см. ensureWords). */
function вместитьСлова(пок, start, core) {
  const предел = Math.max(start + MIN_SPAN, core);
  const i = пок.findIndex((w) => w.end > предел + 0.0005);
  if (i < 0) return пок;
  const левее = i > 0 ? пок[i - 1].end : пок[0].start;
  const от = Math.max(start, Math.min(левее, предел - 0.05));
  const места = разложитьПоВесу(пок.slice(i).map((w) => w.text), от, предел);
  for (let j = i; j < пок.length; j++) {
    пок[j].start = места[j - i].start;
    пок[j].end = места[j - i].end;
  }
  return пок;
}

function lineWords(line, span) {
  const start = span.start;
  const end = span.end;
  const core = span.core != null ? span.core : end;

  if (line.words && line.words.length) {
    const arr = line.words;
    const сдвиг = сдвигСлов(line, span);
    const пок = arr.map((w, i) => ({
      text: w.text,
      /* Начало первого слова НЕ приравнивается к началу строки: если
         человек отодвинул его, метка окажется правее start — и это
         пауза перед первым словом, законная ровно так же, как пауза
         между словами. Певец вступает не сразу. */
      start: w.time + сдвиг,
      end: (w.end != null ? w.end
        : (arr[i + 1] ? arr[i + 1].time : w.time + 0.3)) + сдвиг,
      ручнойКонец: !!w.ручнойКонец,
    }));
    вместитьСлова(пок, start, core);
    // «Свой» конец — до распева. По нему живёт черта внутри блока строки
    // и по нему же пишется разметка, когда слово правят (см. ensureWords)
    пок.forEach((w) => { w.свой = w.end; });
    /* Последнее слово тянется, пока звучит голос: это и есть распев.
       Но конец, выставленный ЧЕЛОВЕКОМ (w.ручнойКонец — тот же признак,
       что line.ручнойКонец у строки), важнее автоматики: тогда хвост
       остаётся за строкой, а слово кончается там, где сказано. */
    const п = пок.length - 1;
    if (!пок[п].ручнойКонец) пок[п].end = Math.max(пок[п].end, end);
    return пок;
  }

  const chunks = splitWords(line.text);
  if (!chunks.length) return [];
  const места = разложитьПоВесу(chunks, start, core);
  const out = chunks.map((text, i) => ({
    text, start: места[i].start, end: места[i].end, свой: места[i].end,
  }));
  // Хвост распева достаётся последнему слову, а не всей строке разом
  out[out.length - 1].end = Math.max(out[out.length - 1].end, end);
  return out;
}

/* Сколько слова уже спето: целые слова закрашены полностью,
   текущее доезжает плавно внутри себя */
function wordProgress(words, pos) {
  const done = [];
  for (let i = 0; i < words.length; i++) {
    const w = words[i];
    if (pos >= w.end) done.push(1);
    else if (pos <= w.start) done.push(0);
    else done.push((pos - w.start) / Math.max(0.03, w.end - w.start));
  }
  return done;
}

/* ============================================================
   Чтение .lrc — обычного и расширенного

   Готовых .lrc в сети тысячи: строка и её время. Открыть такой файл —
   значит получить почти готовую разметку и не размечать песню заново.
   Свои файлы студия пишет тем же форматом (см. экспорт), так что круг
   замыкается: выгрузил, поправил в другом месте, открыл обратно.

   Что понимаем:
     [ti:…] [ar:…] [by:…]     — сведения о песне, запоминаем;
     [offset:+250]            — общий сдвиг в миллисекундах;
     [00:12.34]текст          — строка и её время;
     [00:12.34][01:05.00]…    — один и тот же текст в нескольких местах
                                (припев), разворачиваем в отдельные строки;
     [00:12.34]               — метка без текста: это КОНЕЦ предыдущей
                                строки, а не пустая строка;
     [00:12.34]<00:12.34>Сло<00:12.90>во<00:13.40>
                              — расширенный LRC: метки слов в угловых
                                скобках, последняя закрывает строку.

   Знак offset: положительный сдвигает текст РАНЬШЕ (так его понимают
   плееры, так же пишут и сами файлы), поэтому время = метка − offset.
   ============================================================ */
const LRC_МЕТКА = /\[(\d{1,3}):(\d{1,2})(?:[.:](\d{1,3}))?\]/g;
const LRC_СЛОВО = /<(\d{1,3}):(\d{1,2})(?:[.:](\d{1,3}))?>/g;

function времяLrc(м, с, доли) {
  const дробь = доли == null ? 0 : Number('0.' + доли);
  return Number(м) * 60 + Number(с) + дробь;
}

function разобратьLrc(текст) {
  const мета = {};
  let offset = 0;
  const сырые = [];        // { time, text, words }
  const концы = [];        // метки без текста: закрывают предыдущую строку

  String(текст == null ? '' : текст).replace(/^﻿/, '').split(/\r?\n/).forEach((строка) => {
    const с = строка.trim();
    if (!с) return;

    // Сведения о песне: [ключ:значение] буквами, а не цифрами
    const мет = /^\[([a-zA-Zа-яА-Я]+):(.*)\]$/.exec(с);
    if (мет) {
      const ключ = мет[1].toLowerCase();
      if (ключ === 'offset') offset = (parseFloat(мет[2]) || 0) / 1000;
      else мета[ключ] = мет[2].trim();
      return;
    }

    LRC_МЕТКА.lastIndex = 0;
    const времена = [];
    let м;
    let конецМеток = 0;
    while ((м = LRC_МЕТКА.exec(с))) {
      // Метки идут только В НАЧАЛЕ строки; дальше — уже текст
      if (м.index !== конецМеток) break;
      времена.push(времяLrc(м[1], м[2], м[3]));
      конецМеток = LRC_МЕТКА.lastIndex;
    }
    if (!времена.length) return;              // строка без времени — не наша
    const хвост = с.slice(конецМеток).trim();
    if (!хвост) { концы.push(...времена); return; }

    // Расширенный LRC: метки слов внутри строки
    const слова = [];
    LRC_СЛОВО.lastIndex = 0;
    let место = 0;
    let текущее = null;
    let есть;
    while ((есть = LRC_СЛОВО.exec(хвост))) {
      const кусок = хвост.slice(место, есть.index);
      if (текущее && кусок.trim()) {
        текущее.text = кусок;
        слова.push(текущее);
      }
      const t = времяLrc(есть[1], есть[2], есть[3]);
      // Метка сразу за меткой (или в самом конце) закрывает прошлое слово
      if (слова.length && !кусок.trim()) слова[слова.length - 1].end = t;
      else if (слова.length && слова[слова.length - 1].end == null) {
        слова[слова.length - 1].end = t;
      }
      текущее = { time: t, end: null, text: '' };
      место = LRC_СЛОВО.lastIndex;
    }
    if (текущее) {
      const кусок = хвост.slice(место);
      if (кусок.trim()) { текущее.text = кусок; слова.push(текущее); }
      // Последняя метка без текста — конец строки
      else if (слова.length) слова[слова.length - 1].end = текущее.time;
    }

    const чистый = хвост.replace(LRC_СЛОВО, '').trim();
    if (!чистый) return;
    времена.forEach((t) => {
      const строкаИтог = { time: t, text: чистый };
      if (слова.length > 1 || (слова.length === 1 && слова[0].time !== t)) {
        /* Метки слов абсолютны и относятся к ПЕРВОМУ появлению строки;
           у повторов (припев) сдвигаем их на разницу времён. */
        const сдвиг = t - слова[0].time;
        строкаИтог.words = слова.map((w) => ({
          text: w.text,
          time: w.time + сдвиг,
          end: w.end == null ? null : w.end + сдвиг,
        }));
        const последнее = строкаИтог.words[строкаИтог.words.length - 1];
        if (последнее.end != null) строкаИтог.end = последнее.end;
        строкаИтог.time = строкаИтог.words[0].time;
      }
      сырые.push(строкаИтог);
    });
  });

  сырые.sort((a, b) => a.time - b.time);
  // Метка без текста закрывает ближайшую строку слева от себя
  концы.sort((a, b) => a - b).forEach((к) => {
    for (let i = сырые.length - 1; i >= 0; i--) {
      if (сырые[i].time < к) {
        if (сырые[i].end == null || сырые[i].end > к) сырые[i].end = к;
        break;
      }
    }
  });

  const строки = сырые.map((л) => {
    const итог = { text: л.text, time: Math.max(0, л.time - offset) };
    if (л.end != null) итог.end = Math.max(итог.time + MIN_SPAN, л.end - offset);
    if (л.words) {
      итог.words = л.words.map((w, i) => ({
        text: w.text,
        time: Math.max(0, w.time - offset),
        end: w.end != null ? w.end - offset
          : (л.words[i + 1] ? л.words[i + 1].time - offset : итог.end),
      }));
    }
    return итог;
  });
  return { строки, мета, offset };
}

